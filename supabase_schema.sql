-- Skema PostgreSQL untuk backend aplikasi Absensi PKL.

create table if not exists users (
  id bigint generated by default as identity primary key,
  nama varchar(255) not null unique, password varchar(255) not null,
  role varchar(50) not null default 'mahasiswa', kelompok varchar(100),
  devices jsonb default '[]'::jsonb, max_devices integer default 2,
  created_at timestamptz default now()
);
create table if not exists attendances (
  id bigint generated by default as identity primary key,
  nama varchar(255) not null, kelompok varchar(100), tanggal date not null,
  sesi varchar(20) not null, jam_masuk time, login_time timestamptz,
  status varchar(50) default 'hadir', created_at timestamptz default now(),
  keterangan text, bukti_url text, status_approval text,
  approved_by text, approved_at timestamptz,
  unique (nama, tanggal, sesi)
);
create table if not exists device_bindings (
  id bigint generated by default as identity primary key,
  device_id varchar(255) not null unique, user_name varchar(255) not null,
  kelompok varchar(100), bound_at timestamptz default now(), last_used timestamptz default now(),
  usage_count integer default 1
);
create table if not exists logbook (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade, nama varchar(255) not null,
  kelompok varchar(100), tanggal date not null, kegiatan text not null,
  kendala text, status varchar(20) default 'draft', submitted_at timestamptz,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  unique (nama, tanggal)
);
create table if not exists pendaftar (
  id bigint generated by default as identity primary key,
  nama varchar(255) not null, nim varchar(50) not null, email varchar(255) not null,
  divisi_pilihan varchar(100) not null, divisi_assigned varchar(100),
  status varchar(50) default 'pending', urutan integer not null,
  assigned_at timestamptz, assigned_by varchar(255), created_at timestamptz default now()
);
create table if not exists pendaftar_files (
  id bigint generated by default as identity primary key,
  pendaftar_id bigint not null references pendaftar(id) on delete cascade,
  tipe varchar(50) not null, filename varchar(255) not null, original_name varchar(255) not null,
  file_size integer, mime_type varchar(100), created_at timestamptz default now(), storage_path varchar(500)
);
create table if not exists admin_pendaftaran (
  id bigint generated by default as identity primary key,
  username varchar(100) not null unique, password varchar(255) not null,
  nama varchar(255) not null, created_at timestamptz default now()
);
create table if not exists holidays (
  id bigint generated by default as identity primary key,
  tanggal date not null unique, keterangan varchar(255) not null, created_at timestamptz default now()
);
create table if not exists grading_indicators (
  id bigint generated by default as identity primary key,
  mentor_nama varchar(255) not null, kelompok varchar(100) not null,
  nama_indikator varchar(255) not null, bobot numeric(5,2) default 0,
  urutan integer default 0, created_at timestamptz default now()
);
create table if not exists student_grades (
  id bigint generated by default as identity primary key,
  indicator_id bigint not null references grading_indicators(id) on delete cascade,
  student_nama varchar(255) not null, nilai numeric(5,2), catatan text,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  unique (indicator_id, student_nama)
);
create table if not exists certificates (
  id bigint generated by default as identity primary key,
  student_nama varchar(255) not null, mentor_nama varchar(255), kelompok varchar(100),
  nomor_sertifikat varchar(100) unique, judul varchar(255) default 'Sertifikat Praktik Kerja Lapangan',
  periode_mulai date, periode_selesai date, tanggal_terbit date default current_date,
  catatan text, file_url varchar(500), created_at timestamptz default now()
);
create table if not exists tugas_akhir (
  id bigint generated by default as identity primary key,
  student_nama varchar(255) not null, mentor_nama varchar(255) not null, kelompok varchar(100) not null,
  judul varchar(500) not null, deskripsi text, file_url varchar(500), status varchar(50) default 'pending',
  catatan_mentor text, submitted_at timestamptz, reviewed_at timestamptz,
  created_at timestamptz default now(), updated_at timestamptz default now()
);
create table if not exists tugas_mingguan (
  id bigint generated by default as identity primary key,
  mentor_nama varchar(255) not null, kelompok varchar(100) not null, minggu_ke integer not null,
  judul varchar(255) not null, deskripsi text not null, file_attachment varchar(500),
  deadline timestamptz not null, created_at timestamptz default now(), updated_at timestamptz default now()
);
create table if not exists tugas_mingguan_submissions (
  id bigint generated by default as identity primary key,
  tugas_id bigint not null references tugas_mingguan(id) on delete cascade,
  student_nama varchar(255) not null, kelompok varchar(100) not null, catatan_mahasiswa text,
  file_url varchar(500), link_url varchar(500), nilai numeric(5,2), status varchar(50) default 'submitted',
  catatan_mentor text, submitted_at timestamptz not null, reviewed_at timestamptz,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  unique (tugas_id, student_nama)
);

